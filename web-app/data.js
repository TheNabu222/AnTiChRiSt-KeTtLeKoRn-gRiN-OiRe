    getTotalTrunks: function() {
        return this.trunks.length;
    },
    
    getTotalEntries: function() {
        return this.trunks.reduce((sum, trunk) => sum + trunk.entries.length, 0);
    },
    
    getCategories: function() {
        const categories = new Set();
        this.trunks.forEach(trunk => {
            if (trunk.description) {
                // Extract category from description (e.g., "Aries | Mars | Ontogenesis...")
                const parts = trunk.description.split('|').map(p => p.trim());
                if (parts.length >= 2) {
                    categories.add(parts[0]);
                }
            }
        });
        return Array.from(categories);
    },
    
    search: function(query) {
        const results = [];
        const q = query.toLowerCase();
        
        this.trunks.forEach(trunk => {
            // Search in trunk title and description
            if (trunk.title.toLowerCase().includes(q) || 
                trunk.description.toLowerCase().includes(q)) {
                results.push({
                    type: 'trunk',
                    trunkId: trunk.id,
                    trunkTitle: trunk.title,
                    entryId: null,
                    entryTitle: trunk.title,
                    description: trunk.description
                });
            }
            
            // Search in entries
            trunk.entries.forEach(entry => {
                if (entry.title.toLowerCase().includes(q) || 
                    entry.description.toLowerCase().includes(q) ||
                    entry.id.toLowerCase().includes(q)) {
                    results.push({
                        type: 'entry',
                        trunkId: trunk.id,
                        trunkTitle: trunk.title,
                        entryId: entry.id,
                        entryTitle: entry.title,
                        description: entry.description
                    });
                }
            });
        });
        
        return results;
    },
    
    getTrunkById: function(id) {
        return this.trunks.find(t => t.id === id);
    }
